const mirror = (list) => list.flatMap((b) => [b, [b[0], -b[1], b[2], b[3], b[4]]]);

// 바닥 재질 (발소리): 구역에 surface가 없으면 모래
export function surfaceAt(x, z) {
  const zone = MAP.zones.find((q) => x >= q.x0 && x <= q.x1 && z >= q.z0 && z <= q.z1);
  return zone?.surface || 'sand';
}

